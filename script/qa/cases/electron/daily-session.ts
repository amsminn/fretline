import { expect } from '@playwright/test';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import type { QaCase } from '../../lib/contracts';
import { inspectArchive } from './recovery-support';
import { captureThemes, createFromTemplate, enterFirstNote, noteCount, quitThroughMenu, saveAs, scoreJson, stubSaveDialog, waitForExit, withSessionApp } from './session-support';

export const run: QaCase = async context => {
  const userData = resolve(context.evidence, 'userData');
  await mkdir(userData, { recursive: true });
  const saved = resolve(context.evidence, 'Daily.fretline');
  let before = '';
  const first = await withSessionApp(context, userData, async surface => {
    const { page } = surface;
    await expect(page.getByTestId('home')).toBeVisible();
    await expect(page.getByTestId('recent-empty')).toBeVisible();
    context.assert(await page.locator('[data-template]').count() === 3, 'Home offers guitar, bass and drum templates and no tutorial or account screen');
    await page.screenshot({ path: resolve(context.evidence, 'home-first-launch.png') });
    await createFromTemplate(page, 'guitar');
    await expect(page.getByTestId('document-tab')).toHaveCount(1);
    await expect(page.getByTestId('document-tab').first()).toHaveAttribute('data-dirty', 'false');
    context.assert(await noteCount(page) === 0, 'Guitar template opens clean with empty bars');
    await enterFirstNote(context, page, '3');
    context.assert(await noteCount(page) === 1, 'Typing a fret into the template bar slot creates one note group through the caret');
    await page.screenshot({ path: resolve(context.evidence, 'edited.png') });
    await saveAs(context, surface, saved);
    before = await scoreJson(page);
    const recent = await page.evaluate(() => window.desktop.recentFiles());
    context.assert(recent[0]?.name === 'Daily.fretline' && recent[0].exists, 'Save registers the file in the persisted recent list');
    await page.keyboard.press('Meta+w');
    await expect(page.getByTestId('document-tab')).toHaveCount(0);
    const row = page.getByTestId('recent-document').filter({ has: page.locator('[data-recent-name="Daily.fretline"]') }).or(page.locator('[data-recent-name="Daily.fretline"]'));
    await expect(row.first()).toBeVisible();
    await row.first().hover();
    await row.first().locator('[data-action="pin"]').click();
    await expect(page.locator('[data-recent-name="Daily.fretline"]')).toHaveAttribute('data-pinned', 'true');
    await expect(page.getByTestId('recent-pinned').locator('[data-recent-name="Daily.fretline"]')).toBeVisible();
    context.assert(true, 'Pinning from the Home moves the document into the pinned group');
    await page.keyboard.press('Meta+,');
    await expect(page.getByTestId('preferences-dialog')).toBeVisible();
    await page.getByTestId('theme-select').click();
    await page.getByRole('option', { name: '밝음' }).click();
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
    await page.screenshot({ path: resolve(context.evidence, 'preferences-light.png') });
    await page.keyboard.press('Escape');
    await expect(page.getByTestId('preferences-dialog')).toBeHidden();
    await captureThemes(page, 'home-pinned', context.evidence);
    await page.evaluate(() => { document.documentElement.dataset['theme'] = 'light'; });
  });
  context.assert(first.quitMs >= 0 && first.quitMs < 2_500 && first.exitCode === 0,
    `Cmd+Q-style app.quit() completes through the renderer acknowledgement (${first.quitMs.toFixed(0)} ms, exit ${first.exitCode}) rather than the 3 s fallback`);
  const settings = JSON.parse(await readFile(resolve(userData, 'settings.json'), 'utf8'));
  context.assert(settings.version === 2 && settings.theme === 'light' && settings.recent.some((entry: { path: string; pinned: boolean }) => entry.path === saved && entry.pinned),
    'settings.json persists theme and the pinned recent entry; no loop or selection state is stored');
  context.assert(!('loop' in settings) && !('selection' in settings), 'Persisted settings contain only restart-safe keys');
  const archive = await inspectArchive(saved);
  context.assert(archive.score.tracks[0]?.name === '기타', 'Saved archive decodes independently with the guitar template track');
  const second = await withSessionApp(context, userData, async surface => {
    const { page } = surface;
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
    context.assert(true, 'Light theme is restored after restart');
    await expect(page.getByTestId('home')).toBeVisible();
    const row = page.getByTestId('recent-pinned').locator('[data-recent-name="Daily.fretline"]');
    await expect(row).toBeVisible();
    await page.screenshot({ path: resolve(context.evidence, 'home-after-restart.png') });
    await row.click();
    await expect(page.getByTestId('document-tab')).toHaveCount(1);
    await expect(page.getByTestId('score-view')).toHaveAttribute('aria-busy', 'false', { timeout: 20_000 });
    await expect.poll(() => scoreJson(page)).toBe(before);
    context.assert(true, 'Reopening from the pinned recent entry restores the identical saved document');
    const loop = await page.evaluate(() => window.fretlineLoopObservation?.());
    context.assert(loop?.enabled === false && loop.selection === null, 'A reopened document starts with no loop and no selection');
    await expect(page.getByTestId('document-tab').first()).toHaveAttribute('title', 'Daily.fretline');
    context.assert(true, 'The reopened tab shows the file name, not the score title');
    await page.screenshot({ path: resolve(context.evidence, 'reopened.png') });
    await enterFirstNote(context, page, '5');
    await stubSaveDialog(surface, null);
    await quitThroughMenu(surface.application);
    const prompt = page.getByTestId('save-changes-dialog');
    await expect(prompt).toBeVisible();
    await expect(prompt).toContainText('Daily.fretline');
    await prompt.getByRole('button', { name: '저장', exact: true }).click();
    const exitCode = await waitForExit(surface.application);
    context.assert(exitCode === 0, `Quit -> 저장 writes the existing destination without a picker and exits (code ${exitCode})`);
  });
  context.assert(second.exitCode === 0, 'Second session quits cleanly');
  const resaved = await inspectArchive(saved);
  const notes = resaved.score.tracks.flatMap(track => track.staves.flatMap(staff => staff.voices.flatMap(voice => voice.bars.flatMap(bar =>
    bar.kind === 'active' ? bar.events.filter(event => event.kind === 'noteGroup') : [])))).length;
  context.assert(notes === 2, `The archive saved during quit holds the extra note (${notes} note groups)`);
  await writeFile(resolve(context.evidence, 'session.json'), JSON.stringify({ first, second, settings }, null, 2));
};
